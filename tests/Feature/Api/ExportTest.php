<?php

namespace Tests\Feature\Api;

use App\Models\AttendanceLog;
use App\Models\Device;
use App\Models\Employee;
use App\Models\Tenant;
use App\Models\User;
use App\Support\Tenancy;
use Database\Seeders\DatabaseSeeder;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\Hash;
use Tests\TestCase;

/**
 * The PDF exports, and the filtering they share with the punch log.
 *
 * An export is data LEAVING the system in a file somebody keeps, so the
 * assertions here are about the two ways that goes wrong: the wrong person
 * downloading it, and it covering a different range than its header claims.
 *
 * The generated bytes are checked only for being a real PDF — dompdf's output is
 * compressed, so asserting on its text would be asserting on dompdf. What the
 * document SAYS is fixed by the Blade templates; what it CONTAINS is fixed by
 * the query tests below, which run against the same PunchLogQuery the PDF uses.
 */
class ExportTest extends TestCase
{
    use RefreshDatabase;

    private const PASSWORD = 'test-password';

    private Tenant $acme;

    private Device $device;

    private Employee $employee;

    protected function setUp(): void
    {
        parent::setUp();

        Tenancy::clear();
        $this->seed(DatabaseSeeder::class);
        Tenancy::clear();

        $this->acme = Tenant::where('slug', 'acme')->firstOrFail();
        $this->makeUser('admin@acme.test', 'tenant-admin', $this->acme);
        $this->makeUser('operator@acme.test', 'operator', $this->acme);

        Tenancy::set($this->acme->id);

        $this->device = Device::create([
            'tenant_id' => $this->acme->id,
            'name' => 'IT Room',
            'ip_address' => '192.0.2.20',
            'port' => 4370,
            'protocol' => Device::PROTOCOL_BINARY,
            'is_active' => true,
        ]);

        $this->employee = Employee::where('employee_code', '1001')->firstOrFail();

        Tenancy::clear();
    }

    private function makeUser(string $email, string $role, Tenant $tenant): User
    {
        Tenancy::set($tenant->id);

        $user = User::withoutGlobalScopes()->create([
            'name' => ucfirst($role),
            'email' => $email,
            'password' => Hash::make(self::PASSWORD),
            'tenant_id' => $tenant->id,
            'is_active' => true,
            'email_verified_at' => now(),
        ]);
        $user->syncRoles([$role]);

        Tenancy::clear();

        return $user;
    }

    private function login(string $email)
    {
        $token = $this->postJson('/api/auth/login', [
            'email' => $email,
            'password' => self::PASSWORD,
        ])->json('data.token');

        $this->app['auth']->forgetGuards();

        return $this->withToken($token);
    }

    /** A punch at a given OFFICE-LOCAL wall clock, stored as UTC like the sync does. */
    private function punchAtLocal(string $localWallClock): AttendanceLog
    {
        Tenancy::set($this->acme->id);

        $log = AttendanceLog::create([
            'tenant_id' => $this->acme->id,
            'device_id' => $this->device->id,
            'device_user_id' => $this->employee->employee_code,
            'employee_id' => $this->employee->id,
            'punched_at' => Carbon::parse($localWallClock, config('attendance.timezone'))->utc(),
            'verify_method' => 1,
            'status' => 0,
        ]);

        Tenancy::clear();

        return $log;
    }

    // --- The documents -----------------------------------------------------

    public function test_the_punch_log_exports_as_a_pdf(): void
    {
        $this->punchAtLocal('2026-09-14 08:32');

        $res = $this->login('admin@acme.test')->get('/api/exports/attendance');

        $res->assertOk();
        $this->assertSame('application/pdf', $res->headers->get('content-type'));
        $this->assertStringStartsWith('%PDF-', $res->getContent());
    }

    public function test_one_employees_attendance_exports_as_a_pdf(): void
    {
        $this->punchAtLocal('2026-09-14 08:32');

        $res = $this->login('admin@acme.test')
            ->get("/api/exports/employees/{$this->employee->id}/attendance?from=2026-09-01&to=2026-09-14");

        $res->assertOk();
        $this->assertStringStartsWith('%PDF-', $res->getContent());
    }

    public function test_the_payroll_summary_exports_as_a_pdf(): void
    {
        $res = $this->login('admin@acme.test')->get('/api/exports/payroll?from=2026-09-01&to=2026-09-14');

        $res->assertOk();
        $this->assertStringStartsWith('%PDF-', $res->getContent());
    }

    // --- Who may download what ---------------------------------------------

    /**
     * An operator may read attendance but holds no reports.view, so the payroll
     * summary — salary-adjacent data for every employee — must stay shut to them.
     * The export re-checks the permission itself; it does not rely on the UI
     * hiding a button.
     */
    public function test_payroll_export_is_refused_without_the_reports_permission(): void
    {
        $this->login('operator@acme.test')
            ->getJson('/api/exports/payroll')
            ->assertStatus(403);
    }

    /**
     * An employee-role user holds attendance.view.self only. Their export must
     * be scoped to their own punches, and an employee_id in the query string
     * must not widen it.
     */
    public function test_a_self_only_user_cannot_export_somebody_elses_punches(): void
    {
        Tenancy::set($this->acme->id);
        $other = Employee::where('employee_code', '1002')->firstOrFail();
        Tenancy::clear();

        $staff = $this->makeUser('staff@acme.test', 'employee', $this->acme);
        $staff->forceFill(['employee_id' => $this->employee->id])->save();

        $mine = $this->punchAtLocal('2026-09-14 08:32');

        Tenancy::set($this->acme->id);
        $theirs = AttendanceLog::create([
            'tenant_id' => $this->acme->id,
            'device_id' => $this->device->id,
            'device_user_id' => $other->employee_code,
            'employee_id' => $other->id,
            'punched_at' => now(),
            'verify_method' => 1,
            'status' => 0,
        ]);
        Tenancy::clear();

        // Asking for the other employee by id returns only the caller's own row.
        $listed = $this->login('staff@acme.test')
            ->getJson("/api/attendance?employee_id={$other->id}")
            ->assertOk()
            ->json('data');

        $this->assertSame([$mine->id], array_column($listed, 'id'));
        $this->assertNotContains($theirs->id, array_column($listed, 'id'));

        // The PDF applies the same rule, so it renders rather than 403s.
        $this->login('staff@acme.test')
            ->get("/api/exports/attendance?employee_id={$other->id}")
            ->assertOk();
    }

    // --- The range means what it says --------------------------------------

    /**
     * The filters are OFFICE-LOCAL dates against a UTC column.
     *
     * Both boundaries used to be compared as bare strings, which shifted them by
     * the office offset and made `to` mean midnight rather than end of day. A
     * punch at 01:00 local on the 14th is stored as 22:00 UTC on the 13th, and a
     * punch at 23:00 local on the 14th as 20:00 UTC on the 14th; asking for the
     * 14th must return both, or an export header would name a day it did not
     * actually cover.
     */
    public function test_a_one_day_range_covers_that_whole_local_day(): void
    {
        $earlyHours = $this->punchAtLocal('2026-09-14 01:00');
        $lateEvening = $this->punchAtLocal('2026-09-14 23:00');
        $dayBefore = $this->punchAtLocal('2026-09-13 22:00');
        $dayAfter = $this->punchAtLocal('2026-09-15 00:30');

        $ids = array_column(
            $this->login('admin@acme.test')
                ->getJson('/api/attendance?from=2026-09-14&to=2026-09-14')
                ->assertOk()
                ->json('data'),
            'id',
        );

        sort($ids);
        $expected = [$earlyHours->id, $lateEvening->id];
        sort($expected);

        $this->assertSame($expected, $ids);
        $this->assertNotContains($dayBefore->id, $ids);
        $this->assertNotContains($dayAfter->id, $ids);
    }
}
