    // --- The range means what it says --------------------------------------

    /**
     * The filters are OFFICE-LOCAL dates against a UTC column.
     *
     * Both boundaries used to be compared as bare strings, which shifted them by
     * the office offset and made `to` mean midnight rather than end of day. A
     * punch at 01:00 local on the 14th is stored as 22:00 UTC on the 13th, and a
     * punch at 23:00 local on the 14th as 20:00 UTC on the 14th; asking for the
     * 14th must return both, or an export header would name a day it did not
     * actually cover.
     */
    public function test_a_one_day_range_covers_that_whole_local_day(): void
    {
        $earlyHours = $this->punchAtLocal('2026-09-14 01:00');
        $lateEvening = $this->punchAtLocal('2026-09-14 23:00');
        $dayBefore = $this->punchAtLocal('2026-09-13 22:00');
        $dayAfter = $this->punchAtLocal('2026-09-15 00:30');

        $ids = array_column(
            $this->login('admin@acme.test')
                ->getJson('/api/attendance?from=2026-09-14&to=2026-09-14')
                ->assertOk()
                ->json('data'),
            'id',
        );

        sort($ids);
        $expected = [$earlyHours->id, $lateEvening->id];
        sort($expected);

        $this->assertSame($expected, $ids);
        $this->assertNotContains($dayBefore->id, $ids);
        $this->assertNotContains($dayAfter->id, $ids);
    }
