/**
 * The PDF exports, and the filtering they share with the punch log.
 *
 * An export is data LEAVING the system in a file somebody keeps, so the
 * assertions here are about the two ways that goes wrong: the wrong person
 * downloading it, and it covering a different range than its header claims.
 *
 * The generated bytes are checked only for being a real PDF — dompdf's output is
 * compressed, so asserting on its text would be asserting on dompdf. What the
 * document SAYS is fixed by the Blade templates; what it CONTAINS is fixed by
 * the query tests below, which run against the same PunchLogQuery the PDF uses.
 */
