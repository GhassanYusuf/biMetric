    private function makeUser(string $email, string $role, Tenant $tenant): User
    {
        Tenancy::set($tenant->id);

        $user = User::withoutGlobalScopes()->create([
            'name' => ucfirst($role),
            'email' => $email,
            'password' => Hash::make(self::PASSWORD),
            'tenant_id' => $tenant->id,
            'is_active' => true,
            'email_verified_at' => now(),
        ]);
        $user->syncRoles([$role]);

        Tenancy::clear();

        return $user;
    }

    private function login(string $email)
    {
        $token = $this->postJson('/api/auth/login', [
            'email' => $email,
            'password' => self::PASSWORD,
        ])->json('data.token');

        $this->app['auth']->forgetGuards();

        return $this->withToken($token);
    }

    /** A punch at a given OFFICE-LOCAL wall clock, stored as UTC like the sync does. */
    private function punchAtLocal(string $localWallClock): AttendanceLog
    {
        Tenancy::set($this->acme->id);

        $log = AttendanceLog::create([
            'tenant_id' => $this->acme->id,
            'device_id' => $this->device->id,
            'device_user_id' => $this->employee->employee_code,
            'employee_id' => $this->employee->id,
            'punched_at' => Carbon::parse($localWallClock, config('attendance.timezone'))->utc(),
            'verify_method' => 1,
            'status' => 0,
        ]);

        Tenancy::clear();

        return $log;
    }

